#!/usr/bin/env python3
"""Rebuild ../data/github-evidence.js from evidence_map.json.

For every entry it reads the file from the public repo at its current HEAD commit, finds the line that
matches `pattern`, and writes a link pinned to that commit. If a pattern is not found it stops, so a
claim can never point at code that is gone.

Usage (from the portfolio folder):  python ask-bharati/tools/refresh_github_evidence.py
Needs git on PATH (falls back to the GitHub API, which has a 60 requests/hour anonymous limit; set GITHUB_TOKEN to raise it).
Public repos only. Standard library only.
"""
import json
import os
import re
import subprocess
import sys
import urllib.request
from datetime import date
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "data" / "github-evidence.js"


def fetch(url):
    headers = {"User-Agent": "ask-bharati-evidence"}
    if os.environ.get("GITHUB_TOKEN") and "api.github.com" in url:
        headers["Authorization"] = "Bearer " + os.environ["GITHUB_TOKEN"]
    with urllib.request.urlopen(urllib.request.Request(url, headers=headers), timeout=30) as r:
        return r.read().decode("utf-8", "ignore")


def head_sha(owner, repo):
    """Latest commit of the default branch. `git ls-remote` avoids the anonymous GitHub API rate limit."""
    out = subprocess.run(["git", "ls-remote", f"https://github.com/{owner}/{repo}.git", "HEAD"],
                         capture_output=True, text=True, timeout=60)
    if out.returncode == 0 and out.stdout.strip():
        return out.stdout.split()[0]
    return json.loads(fetch(f"https://api.github.com/repos/{owner}/{repo}/commits/HEAD"))["sha"]


def code_of(path, text):
    if path.endswith(".ipynb"):
        nb = json.loads(text)
        return "\n".join("".join(c["source"]) for c in nb["cells"] if c["cell_type"] == "code")
    return text


def main():
    cfg = json.loads((HERE / "evidence_map.json").read_text(encoding="utf-8"))
    owner, labels = cfg["owner"], cfg["labels"]
    shas, files = {}, {}
    entries = []
    for skill in cfg["skills"]:
        uses = []
        for u in skill["uses"]:
            repo, path = u["repo"], u["file"]
            if repo not in shas:
                shas[repo] = head_sha(owner, repo)
            key = (repo, path)
            if key not in files:
                files[key] = fetch(f"https://raw.githubusercontent.com/{owner}/{repo}/{shas[repo]}/{path}")
            text = code_of(path, files[key])
            m = re.search(u["pattern"], text, re.M | re.I)
            if not m:
                sys.exit(f"pattern not found: {skill['name']} -> {repo}/{path} /{u['pattern']}/")
            line = "" if path.endswith(".ipynb") else "#L%d" % (text[: m.start()].count("\n") + 1)
            url = f"https://github.com/{owner}/{repo}/blob/{shas[repo]}/{path}{line}"
            print("  %-28s %s:%s %s" % (skill["name"], repo, path, text[m.start():m.start()+60].replace("\n"," ")))
            uses.append([labels[repo], path.split("/")[-1], url])
        e = {"n": skill["name"], "re": skill["question_regex"], "uses": uses, "note": skill.get("note", "")}
        if skill.get("say"):
            e["say"] = skill["say"]
        entries.append(e)
    rows = []
    for e in entries:
        say = ("say: %s, " % json.dumps(e["say"])) if "say" in e else ""
        rows.append("    {%sn: %s, re: /%s/i, uses: %s, note: %s}" % (say, json.dumps(e["n"]), e["re"].replace("/", "\\/"), json.dumps(e["uses"]), json.dumps(e["note"])))
    js = (
        "/* GENERATED by tools/refresh_github_evidence.py from tools/evidence_map.json. Do not edit by hand.\n"
        "   Each link is pinned to a commit of a public repo, so it keeps showing what was checked. */\n"
        "(function (AB) {\n  'use strict';\n"
        "  var GH_DATE = '%s';\n  var EV = [\n%s\n  ];\n\n  AB.GH_DATE = GH_DATE; AB.EV = EV;\n})(window.AskBharati = window.AskBharati || {});\n"
        % (date.today().strftime("%-d %b %Y") if os.name != "nt" else date.today().strftime("%d %b %Y").lstrip("0"), ",\n".join(rows))
    )
    OUT.write_text(js, encoding="utf-8")
    print("wrote", OUT, "-", len(entries), "skills,", len(shas), "repos")


if __name__ == "__main__":
    main()
